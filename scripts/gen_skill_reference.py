"""Writes docs/skills.md: every skill and tool, straight from the code.

    python scripts/gen_skill_reference.py

tests/test_docs.py fails when docs/skills.md is out of date, so run this after
adding or changing a skill or tool.
"""

from __future__ import annotations

import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

OUT = ROOT / "docs" / "skills.md"


def render() -> str:
    from winauto.adapters.storage.db import Database
    from winauto.config import Config
    from winauto.core.context import Context
    from winauto.core.skill import Risk
    from winauto.skills import build_registry

    ctx = Context(config=Config(), db=Database(":memory:"), data_dir=Path(tempfile.gettempdir()))
    registry = build_registry(ctx)
    lines = [
        "# Skills and tools reference",
        "",
        "<!-- Generated by scripts/gen_skill_reference.py. Don't edit by hand. -->",
        "",
        f"WinAuto has **{len(registry.skills)} skills** with **{len(registry.tools)} tools**. "
        "The AI model sees each tool's name, description and parameters, and picks the ones a request needs. "
        "Tools marked **asks first** show an approval card before they run.",
        "",
        "To add your own, see [Adding a skill](adding-a-skill.md).",
        "",
        "| Skill | What it does | Tools |",
        "|---|---|---|",
    ]
    by_skill: dict[str, list] = {}
    for t in registry.tools:
        by_skill.setdefault(t.skill, []).append(t)
    for skill in registry.skills:
        lines.append(f"| [{skill.name}](#{skill.name}) | {skill.description} | {len(by_skill.get(skill.name, []))} |")
    for skill in registry.skills:
        lines += ["", f"## {skill.name}", "", skill.description, ""]
        for t in sorted(by_skill.get(skill.name, []), key=lambda t: t.name):
            badge = " · **asks first**" if t.risk is Risk.CONFIRM else ""
            lines.append(f"- **`{t.name}`**{badge}: {t.description}")
            for p in t.params:
                bits = [p.kind if p.kind != "array" else f"list of {p.item_kind or 'string'}"]
                if p.choices:
                    bits.append("one of " + ", ".join(f"`{c}`" for c in p.choices))
                if not p.required:
                    bits.append(f"optional, default `{p.default!r}`" if p.default not in (None, "") else "optional")
                desc = f": {p.description}" if p.description else ""
                lines.append(f"  - `{p.name}` ({'; '.join(bits)}){desc}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUT.write_text(render(), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")
